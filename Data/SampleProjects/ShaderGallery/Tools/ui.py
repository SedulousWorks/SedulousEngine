#!/usr/bin/env python3
"""ui.py: the lesson list on the engine GUI (ui/Gallery.xml, styled by ui/GallerySheet.css; an asset's name is its file's, so the two may not
share one) and the game code's lesson table (../Code/ShaderGallery/src/Lessons.bf), written from
the lessons table (lessons.py): a row per lesson in the list, and a row per lesson in the table
the Gallery behaviour wires the list's rows from.

Run after a change to lessons.py; importui.py then imports the list and the sheet, and the
project's build (Build Project) compiles the table into the game.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from lessons import LESSONS, shader_file

def xml_text(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def beef_text(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def markup():
    rows = []
    for l in LESSONS:
        label = "%d. %s   (%s)" % (l["n"], l["title"], l["kind"])
        rows.append('      <Button id="lesson-%d" class="lesson" text="%s"/>' % (l["n"], xml_text(label)))
    return """<!-- GENERATED by Tools/ui.py from Tools/lessons.py. The lesson list sits in the top left, as tall
     as its rows (so a short window still fits it), with a row per lesson; the Gallery behaviour
     glides the camera to the lesson a row names. What the picked lesson teaches shows in a caption
     at the foot of the free view, which the behaviour hides until a row is clicked. H hides both.
     Styled by GallerySheet.css, the project's GUI sheet. The screen takes none of the hall's input
     (its empty space takes no pointer input, so a drag there looks around), and back (Escape,
     East) leaves the list where it is. -->
<Screen blocks="false" back="none">
<Panel class="gallery">
  <Panel id="gallery-panel" class="gallery-card gallery-list">
    <Label class="gallery-heading" text="Shader Gallery"/>
    <Label class="gallery-lead" text="A lesson per shader: pick one"/>
    <Panel class="gallery-lessons">
%s
    </Panel>
    <Label class="gallery-hint" text="WASD fly, Q/E down and up, Shift faster"/>
    <Label class="gallery-hint" text="Right mouse button: look. H: hide"/>
  </Panel>
  <Panel class="gallery-foot">
    <Panel id="gallery-caption" class="gallery-card gallery-caption">
      <Label id="gallery-title" class="gallery-title" text=""/>
      <Label id="gallery-about" class="gallery-about" text=""/>
      <Label id="gallery-file" class="gallery-file" text=""/>
    </Panel>
  </Panel>
</Panel>
</Screen>
""" % "\n".join(rows)


CSS = """/* GENERATED by Tools/ui.py: the gallery's look, and the project's GUI sheet (guiStyleSheetIds). */
.gallery { flex-direction: row; gap: 16px; padding: 16px; pointer-events: none; }
.gallery-card { pointer-events: auto; padding: 12px; background-color: rgba(11, 14, 20, 0.82); border-radius: 12px; }
.gallery-list { flex-direction: column; align-items: start; align-self: start; gap: 4px; width: 334px; }
.gallery-heading { font-size: 24px; color: #F0F2F8; }
.gallery-lead { font-size: 14px; color: #9AA4B8; margin-bottom: 4px; }
.gallery-lessons { flex-direction: column; gap: 4px; margin-bottom: 6px; }
button.lesson { width: 300px; height: 26px; font-size: 15px; color: #E4E8F0; background-color: #161A22;
                border: 1px solid #2E3644; border-radius: 8px; }
button.lesson:hover { background-color: #202838; border: 2px solid #6A8AC0; }
button.lesson:active { background-color: #2A3448; border: 2px solid #8AB0F0; }
button.lesson:focus-visible { border: 2px solid #8AB0F0; }
.gallery-hint { font-size: 13px; color: #7A8498; }
.gallery-foot { flex-grow: 1; flex-direction: column; justify-content: end; align-items: center; pointer-events: none; }
.gallery-caption { flex-direction: column; align-items: start; gap: 4px; width: 584px; }
.gallery-title { font-size: 20px; color: #F0F2F8; }
.gallery-about { font-size: 15px; color: #C8D0E0; width: 560px; white-space: normal; }
.gallery-file { font-size: 13px; color: #8AB0F0; }
"""


LESSONS_BF = os.path.join(HERE, "..", "Code", "ShaderGallery", "src", "Lessons.bf")


def lessons_bf():
    rows = ",\n".join('\t\tLesson(%d, "%s", "%s", "Sources/%s", "View%02d", "Lesson%02d")'
                        % (l["n"], beef_text(l["title"]), beef_text(l["summary"]), shader_file(l), l["n"], l["n"])
                        for l in LESSONS)
    return """// GENERATED by Tools/ui.py from Tools/lessons.py: edit the table there, not this copy.
using System;

namespace ShaderGallery;

/// The gallery's lessons in teaching order, a row each in the lesson list (its id "lesson-<n>"),
/// each with the viewpoint ("ViewNN") and the exhibit ("LessonNN") the hall gives it.
static class Lessons
{
\tpublic const int Count = %d;

\tpublic static Lesson[Count] All = .(
%s);
}
""" % (len(LESSONS), rows)


if __name__ == "__main__":
    os.makedirs(os.path.join(HERE, "ui"), exist_ok=True)
    open(os.path.join(HERE, "ui", "Gallery.xml"), "w").write(markup())
    open(os.path.join(HERE, "ui", "GallerySheet.css"), "w").write(CSS)
    open(LESSONS_BF, "w").write(lessons_bf())
    print("wrote ui/Gallery.xml, ui/GallerySheet.css and ../Code/ShaderGallery/src/Lessons.bf (%d lessons)" % len(LESSONS))
