#!/usr/bin/env python3
"""ui.py: the lesson list (ui/Gallery.sml) and the camera's script (scripts/Gallery.as), written from
the lessons table (lessons.py): a row per lesson in the list, a click handler per row in the script
(AngelScript makes a callback from a method, not from a number, so each row has its own).

Run after a change to lessons.py or to scripts/Gallery.as.in; importscripts.py then imports both.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from lessons import LESSONS, shader_file

BUTTON_STYLE = ("background: state-list(normal=rounded-rect(#161A22, radius=8, border=#2E3644, border-width=1), "
                "hover=rounded-rect(#202838, radius=8, border=#6A8AC0, border-width=2), "
                "pressed=rounded-rect(#2A3448, radius=8, border=#8AB0F0, border-width=2), "
                "focused=rounded-rect(#161A22, radius=8, border=#8AB0F0, border-width=2)); text-color: #E4E8F0;")


def xml_text(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def as_text(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def sml():
    rows = []
    for l in LESSONS:
        label = "%d. %s   (%s)" % (l["n"], l["title"], l["kind"])
        rows.append('          <Button id="lesson-%d" text="%s" width="300" height="26" font-size="15" '
                    'style="%s"/>' % (l["n"], xml_text(label), BUTTON_STYLE))
    return """<screen mode="overlay">

  <!-- GENERATED by Tools/ui.py from Tools/lessons.py. The lesson list in the top left, as tall as
       its rows (a short window still fits it): a row per lesson (Gallery.as glides the camera to
       it). What the picked lesson teaches shows in a caption at the foot of the free view, hidden
       until a row is clicked. H hides both. -->
  <Flex direction="horizontal" align="stretch" padding="16" spacing="16">
    <Flex direction="vertical" justify="start" align="start">
      <Panel id="gallery-panel" padding="12" style="background: rounded-rect(#0B0E14D0, radius=12);">
        <Flex direction="vertical" align="start" spacing="4" width="310">
          <Label text="Shader Gallery" font-size="24" style="text-color: #F0F2F8;"/>
          <Label text="A lesson per shader: pick one" font-size="14" style="text-color: #9AA4B8;"/>
          <Spacer spacer-height="4"/>
%s
          <Spacer spacer-height="6"/>
          <Label text="WASD fly, Q/E down and up, Shift faster" font-size="13" style="text-color: #7A8498;"/>
          <Label text="Right mouse button: look. H: hide" font-size="13" style="text-color: #7A8498;"/>
        </Flex>
      </Panel>
    </Flex>
    <Flex direction="vertical" justify="end" align="center" flex-grow="1">
      <Panel id="gallery-caption" padding="12" visibility="hidden" style="background: rounded-rect(#0B0E14D0, radius=12);">
        <Flex direction="vertical" align="start" spacing="4" width="560">
          <Label id="gallery-title" text="" font-size="20" style="text-color: #F0F2F8;"/>
          <Label id="gallery-about" text="" font-size="15" width="560" word-wrap="true" style="text-color: #C8D0E0;"/>
          <Label id="gallery-file" text="" font-size="13" style="text-color: #8AB0F0;"/>
        </Flex>
      </Panel>
    </Flex>
  </Flex>

</screen>
""" % "\n".join(rows)


def script():
    template = open(os.path.join(HERE, "scripts", "Gallery.as.in")).read()
    wire = "\n".join('\t\ts.FindButton("lesson-%d").OnClick(ScriptCallback(this.onLesson%d));' % (l["n"], l["n"])
                     for l in LESSONS)
    handlers = "\n".join('\tprivate void onLesson%d() { showLesson(%d, "%s", "%s", "Sources/%s"); }'
                         % (l["n"], l["n"], as_text(l["title"]), as_text(l["summary"]), shader_file(l))
                         for l in LESSONS)
    return template.replace("{{WIRE}}", wire).replace("{{HANDLERS}}", handlers)


if __name__ == "__main__":
    os.makedirs(os.path.join(HERE, "ui"), exist_ok=True)
    open(os.path.join(HERE, "ui", "Gallery.sml"), "w").write(sml())
    open(os.path.join(HERE, "scripts", "Gallery.as"), "w").write(script())
    print("wrote ui/Gallery.sml and scripts/Gallery.as (%d lessons)" % len(LESSONS))
